#!/usr/bin/env python3
"""Regenerate skills/pcb-as-code/api.md from the library's signatures and docstrings.

Run after changing a public function:  python3 scripts/gen_api.py
"""
import ast
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULES = ["kicad/schematic.py", "kicad/verify.py", "kicad/board.py", "kicad/planar.py", "kicad/netlist.py",
           "kicad/fab.py", "kicad/geometry.py", "mcad/probe.py", "mcad/gasket.py", "mcad/printing.py",
           "mcad/render.py"]


def doc(node):
    return " ".join((ast.get_docstring(node) or "").split("\n\n")[0].split())


def main():
    out = ["# hwdesign API", "",
           "Generated by `scripts/gen_api.py` from the source; public names only.", ""]
    for rel in MODULES:
        tree = ast.parse(open(os.path.join(ROOT, "src", "hwdesign", rel)).read())
        mod = "hwdesign." + rel[:-3].replace("/", ".")
        out += ["## `%s`" % mod, "", doc(tree), ""]
        for n in tree.body:
            if isinstance(n, ast.FunctionDef) and not n.name.startswith("_"):
                out.append("- `%s(%s)`: %s" % (n.name, ast.unparse(n.args), doc(n)))
            elif isinstance(n, ast.ClassDef) and not n.name.startswith("_"):
                bases = "(%s)" % ", ".join(ast.unparse(b) for b in n.bases) if n.bases else ""
                out.append("- class `%s%s`: %s" % (n.name, bases, doc(n)))
                for m in n.body:
                    if isinstance(m, ast.FunctionDef) and (not m.name.startswith("_") or m.name == "__init__"):
                        args = ast.unparse(m.args).replace("self, ", "").replace("self", "")
                        out.append("  - `.%s(%s)`: %s" % (m.name, args, doc(m)))
        out.append("")
    with open(os.path.join(ROOT, "skills", "pcb-as-code", "api.md"), "w") as f:
        f.write("\n".join(out).rstrip() + "\n")


if __name__ == "__main__":
    main()
